/* tests/exec/container_queries.c -- container queries case by case, through the cascade and layout: a page laid out in
   an 800x600 viewport, then the boxes of its elements that have an id (their content box, and the text of each line's
   fragments, a ::before's or a marker's among them) and the colour the cascade gave them. Size and inline-size
   containers, their queries and units, nested and named ones, the restyle of a container's subtree once layout sizes it
   (a ::before generated by a query, counters in a container, a container laid out twice as a flex item), a page without
   container queries after pages with them; each case's boxes as Chromium lays them out (tests/pages/container*.html hold
   the same to Chromium). Clean under valgrind: the cascade's kept state and layout's are freed. */
#include <stdio.h>
#include <string.h>
#include <vector.pl>
#include <amb.pl>

amb_interface(dom);
amb_interface(html);
amb_interface(net);
amb_interface(css);
amb_interface(layout);

typedef struct qcase { const char *what; const char *html; } qcase;

static const qcase cases[] = {
    { "an inline-size container's query and units",
      "<style>.c{container-type:inline-size;width:400px}@container (width > 300px){#a{color:red;width:50cqw}}</style>"
      "<div class=c><div id=a>wide</div></div>" },
    { "a size container: its auto height its content's as if empty, its units in both axes",
      "<style>.c{container-type:size;width:300px;padding:5px}#a{width:10cqw;height:20cqh}</style><div id=t class=c><div id=a></div>text</div>" },
    { "nested containers: the nearest answers, a named one by its name",
      "<style>.o{container:outer/inline-size;width:600px}.i{container-type:inline-size;width:50%}"
      "@container (width < 400px){#a{color:green}}@container outer (width > 500px){#b{color:blue}}</style>"
      "<div class=o><div class=i><p id=a>inner</p><p id=b>outer's</p></div></div>" },
    { "a ::before a query generates, counters inside a container",
      "<style>.c{container-type:inline-size;width:300px}@container (width > 200px){#a::before{content:'[' counter(n) '] '}}"
      "body{counter-reset:n 10}#a{counter-increment:n}</style><div class=c><p id=a>x</p></div><p id=b style='counter-increment:n'>y</p>" },
    { "a container as a flex item: laid out at its flexed width, its query answered for it",
      "<style>.c{container-type:inline-size;flex:1}@container (width > 250px){#a{display:none}}@container (width <= 250px){#b{color:red}}</style>"
      "<div id=t style='display:flex;width:500px'><div class=c><span id=a>wide</span><span id=b>narrow</span></div><div style='width:300px'></div></div>" },
    { "a shrinking container is as wide as its own edges",
      "<div id=a style='container-type:inline-size;float:left;padding:4px'>shrink</div>" },
    { "a page with no container query after those with them",
      "<p id=a style='color:red'>plain</p>" },
};

static uint32_t find_id(const dom_document *d, const char *id) {
    uint32_t a = names_find(d, "id", 2);
    size_t n = strlen(id);
    for (uint32_t x = 1; x < d->node_len; x++) {
        if (!d->node[x].live) continue;
        for (uint32_t at = d->node[x].first_attr; at; at = d->attr[at].next)
            if (d->attr[at].name == a && d->attr[at].value.len == n && memcmp(text_ptr(d, d->attr[at].value), id, n) == 0) return x;
    }
    return 0;
}

static void show(const dom_document *d, const css_style *st, const layout_tree *t, const char *id) {
    uint32_t x = find_id(d, id);
    if (!x) return;
    for (uint32_t e = 1; e < st->estyle_len; e++) {
        if (st->estyle[e].node.index != x) continue;
        amb_span c = st->cval[st->estyle[e].first + CSS_PROP_COLOR].text;
        printf("  #%s color %.*s\n", id, (int)c.len, text_ptr(st, c));
    }
    for (uint32_t b = 1; b < t->box_len; b++) {
        if (!t->box[b].live || t->box[b].node.index != x || t->box[b].pseudo) continue;
        printf("  #%s %s: content %g,%g %gx%g\n", id, layout_box_kind_name(t->box[b].kind), t->box[b].x, t->box[b].y, t->box[b].w, t->box[b].h);
        for (uint32_t ln = t->box[b].first_line; ln; ln = t->line[ln].next) {
            printf("    line %gx%g:", t->line[ln].w, t->line[ln].h);
            for (uint32_t fr = t->line[ln].first_frag; fr; fr = t->frag[fr].next) {
                amb_span s = t->frag[fr].text;
                printf(" [%s '%.*s']", layout_frag_kind_name(t->frag[fr].kind), (int)s.len, text_ptr(t, s));
            }
            printf("\n");
        }
    }
    for (uint32_t fr = 1; fr < t->frag_len; fr++)
        if (t->frag[fr].live && t->frag[fr].node.index == x && t->frag[fr].kind == LAYOUT_FRAG_KIND_INLINE)
            printf("  #%s inline: %g,%g %gx%g\n", id, t->frag[fr].x, t->frag[fr].y, t->frag[fr].w, t->frag[fr].h);
}

int main(void) {
    static const char *const ids[] = { "t", "a", "b" };
    for (size_t i = 0; i < sizeof cases / sizeof cases[0]; i++) {
        dom_document d;
        html_parser p;
        css_style st;
        layout_tree t;
        dom_init(&d, 1);
        html_init(&p, 1);
        css_init(&st, 1);
        layout_init(&t, 1);
        vector<char> src;
        append_range(src, "<!DOCTYPE html><style>body{margin:8px;font:16px/20px sans-serif}</style>", 74);
        append_range(src, cases[i].html, strlen(cases[i].html));
        html_parse(&p, &d, data(src), len(src));
        css_cascade(&st, &d, 0);
        layout_status s = layout_run(&t, &d, &st, 0, 800, 600);
        printf("%s (%s, invariants: %d broken)\n", cases[i].what, layout_status_name(s), layout_check_invariants(&t, stdout));
        for (size_t k = 0; k < sizeof ids / sizeof ids[0]; k++) show(&d, &st, &t, ids[k]);
    }
    return 0;
}
