%% prolog/amb/gen_schema.pl -- what the contract tool writes for cocolog: the
%% contract's fingerprint, the reasoning schema and the contract's reference.
%%
%%   amb_contract_fingerprint(+M, -FP)   'fnv1a32:HHHHHHHH:N' over the canonical text
%%   amb_schema_text(+M, -Codes)         build/schema/M.pl, the reasoner's view of M
%%   amb_doc_text(+M, -Codes)            the contract as Markdown
%%
%% THE FINGERPRINT IS COMPUTED HERE ONLY. The C generator (gen_c.pl) calls this
%% same predicate at read time and compiles the answer into the module, the
%% schema carries it, and every snapshot is stamped with it: the reasoner refuses
%% a snapshot whose module was built from another text of the contract.
%% Its predicates are amb_* for the public three and ambs_* for the helpers.
:- ensure_loaded(library(amb/contract)).

%% ---- the fingerprint --------------------------------------------------------

%% the canonical text: each declaration written quoted, its variables named in
%% order, a full stop and a newline after each, in the contract's order
amb_contract_canonical(M, Codes) :-
    amb_contract_terms(M, Ds),
    ambs_canonical(Ds, Codes).

ambs_canonical([], []).
ambs_canonical([D|Ds], Codes) :-
    ambs_term_codes(D, C),
    ambs_canonical(Ds, Rest),
    append(C, Rest, Codes).

ambs_term_codes(T, Codes) :-
    copy_term(T, T2), numbervars(T2, 0, _),
    format(codes(Codes), '~W.~n', [T2, [quoted(true), numbervars(true)]]).

amb_contract_fingerprint(M, FP) :-
    amb_contract_canonical(M, Codes),
    ambs_fnv1a(Codes, 2166136261, H),
    length(Codes, N),
    ambs_hex8(H, Hex),
    format(atom(FP), 'fnv1a32:~w:~d', [Hex, N]).

%% FNV-1a over 32 bits: each code xor'd in, then multiplied, kept to 32 bits
ambs_fnv1a([], H, H).
ambs_fnv1a([C|Cs], H0, H) :-
    H1 is ((H0 xor C) * 16777619) /\ 0xFFFFFFFF,
    ambs_fnv1a(Cs, H1, H).

ambs_hex8(H, Hex) :-
    format(atom(A), '~16r', [H]), atom_length(A, L),
    Pad is 8 - L,
    (   Pad > 0 -> length(Zs, Pad), maplist(=(0'0), Zs), atom_codes(Z, Zs), atom_concat(Z, A, Hex)
    ;   Hex = A
    ).

%% ---- the schema -------------------------------------------------------------
%% M_schema/1 facts, one predicate a module (as a contract is one), so that two
%% modules' schemas load side by side in cocolog's one namespace.

amb_schema_text(M, Codes) :-
    amb_contract_terms(M, Ds),
    amb_contract_fingerprint(M, FP),
    amb_contract_file(M, File), file_base_name(File, Base),
    member(module(M, Version, Summary), Ds), !,
    atom_concat(M, '_schema', P),
    findall(S, ambs_schema_decl(M, Ds, S), Ss0),
    Ss = [module(M, Version, FP), summary(Summary)|Ss0],
    format(codes(Head),
           '%% build/schema/~w.pl -- the reasoning schema of ~w, generated by tools/amb from contracts/~w.~n%% Do not edit: change the contract and run `make schema`.~n',
           [M, M, Base]),
    findall(C, ( member(S, Ss), T =.. [P, S], ambs_schema_term_codes(T, C) ), Cs),
    append([Head|Cs], Codes).

%% a schema declaration written as the canonical text writes it, but a variable that
%% occurs once as _: a query's anonymous variables, which a reader would otherwise
%% warn of. (The fingerprint's canonical text is ambs_canonical's, unchanged.)
ambs_schema_term_codes(T, Codes) :-
    copy_term(T, T2), numbervars(T2, 0, _, [singletons(true)]),
    format(codes(Codes), '~W.~n', [T2, [quoted(true), numbervars(true)]]).

ambs_schema_decl(_, Ds, handle(R, F)) :- member(handle(R, F), Ds).
ambs_schema_decl(_, Ds, enum(E, Vs)) :- member(enum(E, Vs), Ds).
ambs_schema_decl(_, Ds, status(Codes)) :- member(status(Codes), Ds).
ambs_schema_decl(_, Ds, fact(F/A, Shapes)) :-
    member(fact(Head, table(R), _), Ds),
    functor(Head, F, A), Head =.. [_|Args],
    maplist(ambs_arg_shape(Ds, R), Args, Shapes).
ambs_schema_decl(_, Ds, derived(PI, Text)) :- member(derived(PI, Text), Ds).
ambs_schema_decl(_, Ds, rules(File)) :- member(rules(File), Ds).
ambs_schema_decl(_, Ds, operation(Op, Types, Res, Opts)) :-
    member(operation(Op, Ps, Res, _, _, Opts), Ds),
    findall(T, member(param(_, T), Ps), Types).
ambs_schema_decl(_, Ds, query(Name, Goal, Vars, Text)) :- member(query(Name, Goal, Vars, Text), Ds).

%% the shape of a fact's argument, which the reasoner checks each snapshot line against
ambs_arg_shape(Ds, R, handle, handle(R)) :- memberchk(handle(R, _), Ds), !.
ambs_arg_shape(_, _, doc, integer) :- !.
ambs_arg_shape(_, _, rev, integer) :- !.
ambs_arg_shape(Ds, R, field(F), Shape) :-
    ambc_field(Ds, R, F, T), ambs_type_shape(T, Shape).

ambs_type_shape(ref(R), handle_or_none(R)) :- !.
ambs_type_shape(xhandle(M, R), xhandle(M, R)) :- !.
ambs_type_shape(enum(E), enum(E)) :- !.
ambs_type_shape(atom(_), atom) :- !.
ambs_type_shape(span(_), atom) :- !.
ambs_type_shape(bool, enum_values([true, false])) :- !.
ambs_type_shape(f64, number) :- !.
ambs_type_shape(_, integer).

%% ---- the reference ----------------------------------------------------------

amb_doc_text(M, Codes) :-
    amb_contract_terms(M, Ds),
    amb_contract_fingerprint(M, FP),
    member(module(M, Version, Summary), Ds), !,
    findall(C, ambs_doc_part(Ds, C), Cs),
    format(codes(Head),
           '# Module `~w` ~w~n~n~w~n~n*Generated by `tools/amb doc ~w` from `contracts/~w.pl`; fingerprint `~w`.*~n',
           [M, Version, Summary, M, M, FP]),
    append([Head|Cs], Codes).

ambs_doc_part(Ds, C) :-
    member(status(Codes), Ds),
    atomic_list_concat(Codes, '`, `', S),
    format(codes(C), '~n## Status codes~n~n`~w`~n', [S]).
ambs_doc_part(Ds, C) :-
    findall(L, ( member(enum(E, Vs), Ds), atomic_list_concat(Vs, ', ', VA),
                 format(codes(L), '| `~w` | ~w |~n', [E, VA]) ), Ls),
    Ls \== [],
    append(Ls, Body),
    format(codes(H), '~n## Enums~n~n| enum | values |~n|---|---|~n', []),
    append(H, Body, C).
ambs_doc_part(Ds, C) :-
    member(record(R, Fs), Ds),
    findall(L, ( member(field(F, T), Fs), format(codes(L), '| `~w` | `~q` |~n', [F, T]) ), Ls),
    append(Ls, Body),
    ( member(handle(R, Fn), Ds) -> format(atom(HA), ' -- handle `~w(Doc, Index, Gen)`', [Fn]) ; HA = '' ),
    format(codes(H), '~n## Record `~w`~w~n~n| field | type |~n|---|---|~n', [R, HA]),
    append(H, Body, C).
ambs_doc_part(Ds, C) :-
    member(store(S, Parts), Ds),
    format(codes(C), '~n## Store `~w`~n~n~q~n', [S, Parts]).
ambs_doc_part(Ds, C) :-
    findall(L, ( member(owns(O, X, How), Ds), format(codes(L), '- `~w` owns `~w` (~q)~n', [O, X, How]) ), Ls),
    Ls \== [],
    append(Ls, Body),
    format(codes(H), '~n## Ownership~n~n', []),
    append(H, Body, C).
ambs_doc_part(Ds, C) :-
    findall(L, ( member(operation(Op, Ps, Res, Pres, _, Opts), Ds),
                 findall(PT, ( member(param(PN, PTy), Ps), format(atom(PT), '~w: ~q', [PN, PTy]) ), PTs),
                 atomic_list_concat(PTs, ', ', PA),
                 findall(PC, ( member(pre(Cd, St), Pres), format(atom(PC), '~q -> ~w', [Cd, St]) ), PCs),
                 atomic_list_concat(PCs, '; ', PrA),
                 atomic_list_concat(Opts, ', ', OA),
                 format(codes(L), '| `~w` | ~w | `~q` | ~w | ~w |~n', [Op, PA, Res, PrA, OA]) ), Ls),
    Ls \== [],
    append(Ls, Body),
    format(codes(H), '~n## Operations~n~n| operation | parameters | result | preconditions (failing status) | options |~n|---|---|---|---|---|~n', []),
    append(H, Body, C).
ambs_doc_part(Ds, C) :-
    findall(L, ( member(invariant(N, T, Ch), Ds), format(codes(L), '| `~w` | ~w | `~q` |~n', [N, T, Ch]) ), Ls),
    Ls \== [],
    append(Ls, Body),
    format(codes(H), '~n## Invariants~n~n| invariant | meaning | generated check |~n|---|---|---|~n', []),
    append(H, Body, C).
ambs_doc_part(Ds, C) :-
    findall(L, ( member(fact(Hd, Src, W), Ds), format(codes(L), '| `~q` | `~q` | `~q` |~n', [Hd, Src, W]) ), Ls),
    Ls \== [],
    append(Ls, Body),
    format(codes(H), '~n## Facts exported to cocolog~n~n| fact | source | where |~n|---|---|---|~n', []),
    append(H, Body, C).
ambs_doc_part(Ds, C) :-
    findall(L, ( member(derived(PI, T), Ds), format(codes(L), '| `~w` | ~w |~n', [PI, T]) ), Ls),
    Ls \== [],
    append(Ls, Body),
    format(codes(H), '~n## Derived predicates~n~n| predicate | meaning |~n|---|---|~n', []),
    append(H, Body, C).
