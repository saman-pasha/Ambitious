#!/usr/bin/env python3
"""tools/gen-hyph.py EN-US EN-GB > src/layout/hyph_data.h -- the hyphenation patterns Chromium hyphenates English
by, American and British, as the C tables src/layout/layout.c's hyphenator reads: every pattern as its letters and,
after them, the values between them (Liang's digits, a byte each), in one string; the exceptions as words with
their hyphens. The files' notices come with them, as their licences ask.

EN-US and EN-GB are TeX/en-US and TeX/en-GB of Android's external/hyphenation-patterns, the files Chromium's
hyph-en-us.hyb and hyph-en-gb.hyb are made from (https://android.googlesource.com/platform/external/
hyphenation-patterns): hyph-en-us.pat.txt, a pattern a line (hyph-utf8's hyph-en-us.tex, ushyphmax, less the
patterns its end had computed from TUGboat's exception log), hyph-en-us.hyp.txt, an exception a line (Knuth's and
TUGboat's, ushyphex.tex, whose notice is read from it), hyph-en-us.lic.txt, the patterns' notice; and
hyph-en-gb.pat.txt, hyph-en-gb.hyp.txt and hyph-en-gb.lic.txt (ukhyphen.tex, under the Unicode licence)."""
import os
import sys


def read_set(root, tag):
    pats = open(os.path.join(root, "hyph-%s.pat.txt" % tag), encoding="utf-8").read().split()
    exc = open(os.path.join(root, "hyph-%s.hyp.txt" % tag), encoding="utf-8").read().split()
    notice = []
    for line in open(os.path.join(root, "hyph-%s.lic.txt" % tag), encoding="utf-8").read().split("\n"):
        notice.append(line[1:].rstrip() if line.startswith("%") else line.rstrip())
    while notice and not notice[-1]:
        notice.pop()
    for p in pats:
        if not all(c.isdigit() or c == "." or "a" <= c <= "z" for c in p):
            sys.exit("gen-hyph: a pattern not of a to z: " + p)
    for e in exc:
        if not all(c == "-" or "a" <= c <= "z" for c in e):
            sys.exit("gen-hyph: an exception not of a to z: " + e)
    # each pattern: its letters, then a value for each place between and around them
    out = []
    longest = 0
    for p in pats:
        letters = "".join(c for c in p if not c.isdigit())
        values = [0] * (len(letters) + 1)
        k = 0
        for ch in p:
            if ch.isdigit():
                values[k] = int(ch)
            else:
                k += 1
        longest = max(longest, len(letters))
        out.append(letters + "".join(chr(ord("0") + v) for v in values))
    return out, exc, notice, longest


def strings(w, name, items):
    w("static const char %s[] =\n" % name)
    line = ""
    for p in items:
        if len(line) + len(p) + 1 > 92:
            w('    "%s"\n' % line)
            line = ""
        line += p + " "
    if line:
        w('    "%s"\n' % line)
    w("    ;\n")


def main():
    us, usx, usn, usl = read_set(sys.argv[1], "en-us")
    gb, gbx, gbn, gbl = read_set(sys.argv[2], "en-gb")
    exnotice = []
    for line in open(os.path.join(sys.argv[1], "ushyphex.tex"), encoding="utf-8").read().split("\n"):
        if not line.startswith("%"):
            break
        exnotice.append(line[1:].rstrip())
    w = sys.stdout.write
    w("/* src/layout/hyph_data.h -- generated by tools/gen-hyph.py from Android's hyphenation patterns of English\n")
    w("   (TeX/en-US and TeX/en-GB: hyph-en-us.pat.txt and .hyp.txt, hyph-en-gb.pat.txt and .hyp.txt), the ones\n")
    w("   Chromium's hyph-en-us.hyb and hyph-en-gb.hyb are made from. Do not edit; run the script. Each set's patterns\n")
    w("   (American English: Liang's, Knuth's and Kuiken's; British English: Wujastyk's and Toal's), each as its letters\n")
    w("   and then the values between them, one string a pattern; and its exceptions (Knuth's and TUGboat's; the British\n")
    w("   file's own), their hyphens written. Android took the American patterns from hyph-utf8's hyph-en-us.tex, less\n")
    w("   the ones its end had computed from TUGboat's exception log, and the exceptions from TUGboat's ushyphex.tex.\n")
    w("   The files are modified here in their form alone, not in what they hold: each pattern's digits written after\n")
    w("   its letters, the patterns and exceptions joined into strings.\n\n")
    w("   The American patterns' notice:\n\n")
    for line in usn:
        w(("   " + line).rstrip().replace("*/", "* /") + "\n")
    w("\n   The American exceptions' notice:\n\n")
    for line in exnotice:
        w(("   " + line).rstrip().replace("*/", "* /") + "\n")
    w("\n   The British patterns' notice:\n\n")
    for line in gbn:
        w(("   " + line).rstrip().replace("*/", "* /") + "\n")
    w("*/\n\n")
    w("#define AMB_HYPH_COUNT %d\n" % len(us))
    w("#define AMB_HYPH_LONGEST %d\n" % usl)
    w("#define AMB_HYPH_EXCEPTIONS %d\n" % len(usx))
    w("#define AMB_HYPH_GB_COUNT %d\n" % len(gb))
    w("#define AMB_HYPH_GB_LONGEST %d\n" % gbl)
    w("#define AMB_HYPH_GB_EXCEPTIONS %d\n" % len(gbx))
    strings(w, "amb_hyph_patterns", us)
    strings(w, "amb_hyph_exceptions", usx)
    strings(w, "amb_hyph_gb_patterns", gb)
    strings(w, "amb_hyph_gb_exceptions", gbx)


if __name__ == "__main__":
    main()
