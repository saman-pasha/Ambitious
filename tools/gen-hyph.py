#!/usr/bin/env python3
"""tools/gen-hyph.py PATTERNS.tex > src/layout/hyph_data.h -- the hyphenation patterns of a
TeX pattern file (hyph-utf8's hyph-en-us.tex: Liang's patterns, Knuth's and Kuiken's) and
its exceptions, as the C tables src/layout/layout.c's hyphenator reads: every pattern as
its letters and, after them, the values between them (Liang's digits, a byte each), in one
string; the exceptions as words with their hyphens. The file's notice comes with them, as
its licence asks.

The patterns come from \\patterns{...} and the exceptions from \\hyphenation{...}; a
comment runs from % to the line's end."""
import re
import sys


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    notice = []
    for line in src.split("\n"):
        if not line.startswith("%"):
            break
        notice.append(line[1:].rstrip())
    body = re.sub(r"%[^\n]*", "", src)
    pats = re.search(r"\\patterns\s*\{([^}]*)\}", body).group(1).split()
    exc = re.search(r"\\hyphenation\s*\{([^}]*)\}", body)
    exc = exc.group(1).split() if exc else []
    # each pattern: its letters, then a value for each place between and around them
    out = []
    longest = 0
    for p in pats:
        letters = re.sub(r"[0-9]", "", p)
        values = [0] * (len(letters) + 1)
        k = 0
        for ch in p:
            if ch.isdigit():
                values[k] = int(ch)
            else:
                k += 1
        longest = max(longest, len(letters))
        out.append(letters + "".join(chr(ord("0") + v) for v in values))
    w = sys.stdout.write
    w("/* src/layout/hyph_data.h -- generated by tools/gen-hyph.py from %s. Do not edit;\n" % sys.argv[1].split("/")[-1])
    w("   run the script. The hyphenation patterns of American English (Liang's, Knuth's\n")
    w("   and Kuiken's), each as its letters and then the values between them, one\n")
    w("   string a pattern; and the exceptions, their hyphens written. The file's notice:\n\n")
    for line in notice:
        w(("  " + line).rstrip() + "\n")
    w("*/\n\n")
    w("#define AMB_HYPH_COUNT %d\n" % len(out))
    w("#define AMB_HYPH_LONGEST %d\n" % longest)
    w("static const char amb_hyph_patterns[] =\n")
    line = ""
    for p in out:
        if len(line) + len(p) + 1 > 92:
            w('    "%s"\n' % line)
            line = ""
        line += p + " "
    if line:
        w('    "%s"\n' % line)
    w("    ;\n")
    w("static const char amb_hyph_exceptions[] = \"%s\";\n" % " ".join(exc))


if __name__ == "__main__":
    main()
