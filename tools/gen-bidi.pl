#!/usr/bin/env perl
# tools/gen-bidi.pl > src/layout/bidi_data.h -- the tables of the Unicode Bidirectional
# Algorithm (UAX #9) that layout reads (src/layout/layout.c), from perl's own
# Unicode::UCD (its Unicode version is the tables'): every code point's Bidi_Class, the
# paired brackets (Bidi_Paired_Bracket and its type, for rule N0) and the mirrored
# glyphs (Bidi_Mirroring_Glyph, BidiMirroring.txt's pairs, for rule L4). Run it again
# when a newer Unicode is wanted; the header is committed, so a build needs no perl.
use strict;
use warnings;
use Unicode::UCD qw(prop_invmap);

# the classes in layout.c's order (its BC_ enum)
my @classes = qw(L R AL EN ES ET AN CS NSM BN B S WS ON LRE LRO RLE RLO PDF LRI RLI FSI PDI);
my %index;
@index{@classes} = (0 .. $#classes);

my ($starts, $vals) = prop_invmap('Bidi_Class');
my @ranges;
for my $i (0 .. $#$starts) {
    my $c = $index{$vals->[$i]};
    die "unknown class $vals->[$i]\n" unless defined $c;
    next if @ranges && ($ranges[-1] & 31) == $c;      # the same class as the range before: one range
    push @ranges, ($starts->[$i] << 5) | $c;
}

my ($bs, $bv) = prop_invmap('Bidi_Paired_Bracket');
my ($ts, $tv) = prop_invmap('Bidi_Paired_Bracket_Type');
my %type;
for my $i (0 .. $#$ts) {
    next if lc $tv->[$i] eq 'n';
    my $end = $i < $#$ts ? $ts->[$i + 1] - 1 : 0x10FFFF;
    $type{$_} = $tv->[$i] for $ts->[$i] .. $end;
}
my @brackets;
for my $i (0 .. $#$bs) {
    next if $bv->[$i] eq '';
    my $cp = $bs->[$i];
    next unless lc($type{$cp} // '') eq 'o';
    push @brackets, $cp, $bv->[$i] + 0;
}

my ($ms, $mv) = prop_invmap('Bidi_Mirroring_Glyph');
my @mirror;
for my $i (0 .. $#$ms) {
    next if $mv->[$i] eq '';
    push @mirror, $ms->[$i], $mv->[$i] + 0;
}

sub table {
    my ($name, $what, @v) = @_;
    my $out = "static const uint32_t $name\[" . scalar(@v) . "] = {\n";
    for (my $i = 0; $i < @v; $i += 8) {
        my $end = $i + 7 < $#v ? $i + 7 : $#v;
        $out .= "    " . join(", ", map { sprintf "0x%x", $_ } @v[$i .. $end]) . ",\n";
    }
    return "/* $what */\n$out};\n";
}

my $u = Unicode::UCD::UnicodeVersion();
print <<"END";
/* src/layout/bidi_data.h -- generated by tools/gen-bidi.pl from Unicode $u (perl's
   Unicode::UCD); do not edit. The Unicode Bidirectional Algorithm's data (UAX #9),
   which src/layout/layout.c reads. */
#ifndef AMB_BIDI_DATA_H
#define AMB_BIDI_DATA_H
#include <stdint.h>

END
print table('amb_bidi_class', "every code point's Bidi_Class: ranges in order, each its first code point << 5 | its class (layout.c's BC_ order: " .
            join(' ', @classes) . "); a code point's is its range's, the last that starts at or before it", @ranges), "\n";
print table('amb_bidi_brackets', 'the paired brackets (Bidi_Paired_Bracket, BidiBrackets.txt): each opening one, then its closing one, in order of the first', @brackets), "\n";
print table('amb_bidi_mirror', "the mirrored glyphs (Bidi_Mirroring_Glyph, BidiMirroring.txt's pairs): each code point, then its mirror, in order of the first", @mirror), "\n";
print "#endif\n";
