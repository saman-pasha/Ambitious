#!/usr/bin/env python3
"""tools/gen-entities.py -- writes src/html/entities.h, the HTML named character
references (WHATWG HTML 13.5), from Python's own copy of that table
(html.entities.html5). Run it again only if the table changes:

    python3 tools/gen-entities.py > src/html/entities.h

The C table holds no pointer: every name is a run of one string, by offset and
length, sorted by bytes, so the tokenizer searches it with no pointer kept."""
import html.entities

names = sorted(html.entities.html5.keys(), key=lambda k: k.encode())
blob = "".join(names)
print("/* src/html/entities.h -- generated by tools/gen-entities.py from Python's html.entities.html5,")
print("   the WHATWG table of named character references. Do not edit. */")
print("#define HTML_ENTITY_COUNT %d" % len(names))
print("#define HTML_ENTITY_LONGEST %d" % max(len(n) for n in names))
print("static const char html_entity_names[] =")
for i in range(0, len(blob), 96):
    print('    "%s"' % blob[i:i + 96])
print(";")
print("static const struct html_entity { uint32_t off; uint8_t len; uint32_t cp1, cp2; } html_entities[] = {")
off = 0
for n in names:
    cps = [ord(c) for c in html.entities.html5[n]]
    cp2 = cps[1] if len(cps) > 1 else 0
    print("    { %d, %d, 0x%X, 0x%X }," % (off, len(n), cps[0], cp2))
    off += len(n)
print("};")
