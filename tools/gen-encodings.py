#!/usr/bin/env python3
"""tools/gen-encodings.py [DIR] -- writes src/html/encoding_tables.h, the tables of the
WHATWG Encoding standard (https://encoding.spec.whatwg.org/) that src/html/encoding.c
decodes with: the encodings in the standard's order, their names and every label, and
the indexes the decoders read, from the standard's own files:

    python3 tools/gen-encodings.py > src/html/encoding_tables.h       (fetches them)
    python3 tools/gen-encodings.py DIR > src/html/encoding_tables.h   (DIR holds them)

The files are encodings.json and index-NAME.txt for each index a decoder reads. Each
index's Identifier and Date are written into the header, so it says which revision
of the standard it holds. The output is a function of the files alone.

The C tables hold no pointer. An index is an array by pointer of its code points,
0 where the index has none (no index maps a pointer to U+0000). index Big5 is the only
one past the Basic Multilingual Plane, and all of it that is lies in plane 2: its
array holds a code point's low 16 bits and a bitset says which are plane 2's. Labels
are runs of one string, sorted by bytes, searched with no pointer kept."""
import json
import os
import sys
import urllib.request

BASE = "https://encoding.spec.whatwg.org/"


def fetch(name):
    if len(sys.argv) > 1:
        with open(os.path.join(sys.argv[1], name), "rb") as f:
            return f.read().decode("utf-8")
    with urllib.request.urlopen(BASE + name, timeout=60) as r:
        return r.read().decode("utf-8")


def index(name):
    """an index file: its pointers' code points, its identifier and its date"""
    text = fetch("index-%s.txt" % name)
    table, ident, date = {}, "?", "?"
    for line in text.split("\n"):
        if line.startswith("# Identifier:"):
            ident = line.split(":", 1)[1].strip()
        elif line.startswith("# Date:"):
            date = line.split(":", 1)[1].strip()
        if line == "" or line.startswith("#"):
            continue
        cols = line.split("\t")
        table[int(cols[0])] = int(cols[1], 16)
    return table, ident, date


def c_name(name):
    return "HTML_ENC_" + name.upper().replace("-", "_")


groups = json.loads(fetch("encodings.json"))
encodings = [e for g in groups for e in g["encodings"]]
names = [e["name"] for e in encodings]
single = [e["name"] for g in groups if g["heading"] == "Legacy single-byte encodings" for e in g["encodings"]]
first_single, last_single = names.index(single[0]), names.index(single[-1])
assert names[first_single:last_single + 1] == single

sources = []          # each index read: its file, identifier, date
out = []
w = out.append


def index_of(name):
    table, ident, date = index(name)
    sources.append(("index-%s.txt" % name, ident, date))
    return table


def array(ctype, cname, values, per=20):
    w("static const %s %s[%d] = {" % (ctype, cname, len(values)))
    for i in range(0, len(values), per):
        w("    " + ",".join(str(v) for v in values[i:i + per]) + ",")
    w("};")


def dense(table, size):
    vals = [table.get(p, 0) for p in range(size)]
    assert all(0 < v <= 0xFFFF for v in vals if v)
    return vals


# the index each single-byte encoding reads: its own, but ISO-8859-8-I reads ISO-8859-8's
read = {}
single_tables = []
for n in single:
    file = "iso-8859-8" if n == "ISO-8859-8-I" else n.lower()
    if file not in read:
        t = index_of(file)
        assert set(t) <= set(range(128))
        read[file] = [t.get(b, 0) for b in range(128)]
    single_tables.append(read[file])

jis0208 = index_of("jis0208")
jis0212 = index_of("jis0212")
euc_kr = index_of("euc-kr")
gb18030 = index_of("gb18030")
ranges = index_of("gb18030-ranges")
big5 = index_of("big5")

# each pointer's bound, from the decoders' arithmetic (src/html/encoding.c)
JIS0208_SIZE = (0xFC - 0xC1) * 188 + 0xFC - 0x41 + 1      # Shift_JIS's last pointer, 11279
JIS0212_SIZE = (0xFE - 0xA1) * 94 + 0xFE - 0xA1 + 1       # EUC-JP's, 8835
EUC_KR_SIZE = (0xFE - 0x81) * 190 + 0xFE - 0x41 + 1       # 23939
GB18030_SIZE = (0xFE - 0x81) * 190 + 0xFE - 0x41 + 1      # 23939
BIG5_SIZE = (0xFE - 0x81) * 157 + 0xFE - 0x62 + 1         # 19781
for t, size in ((jis0208, JIS0208_SIZE), (jis0212, JIS0212_SIZE), (euc_kr, EUC_KR_SIZE), (gb18030, GB18030_SIZE), (big5, BIG5_SIZE)):
    assert max(t) < size

labels = sorted(((l, names.index(e["name"])) for e in encodings for l in e["labels"]), key=lambda x: x[0].encode())
assert len(set(l for l, _ in labels)) == len(labels)
blob = "".join(l for l, _ in labels)

w("/* src/html/encoding_tables.h -- generated by tools/gen-encodings.py from the WHATWG Encoding")
w("   standard (https://encoding.spec.whatwg.org/): its encodings, their names and labels")
w("   (encodings.json), and the indexes its decoders read, each file below with its")
w("   Identifier and Date. Do not edit; run the script. src/html/encoding.c reads them.")
w("")
for f, ident, date in sources:
    w("   %-28s %s  %s" % (f, date, ident))
w("")
w("   An index here is an array by pointer of its code points, 0 where it has none. */")
w("")
w("/* the encodings, in the standard's order (its table in 4.2, Names and labels) */")
w("enum html_enc {")
for i in range(0, len(names), 6):
    w("    " + " ".join(c_name(n) + "," for n in names[i:i + 6]))
w("};")
w("#define HTML_ENC_COUNT %d" % len(names))
w("/* the single-byte encodings, %s to %s, in html_enc_single's order */" % (single[0], single[-1]))
w("#define HTML_ENC_SINGLE_FIRST %s" % c_name(single[0]))
w("#define HTML_ENC_SINGLE_LAST %s" % c_name(single[-1]))
w("")
w("/* each encoding's name, as the standard writes it */")
w("static const char *const html_enc_names[HTML_ENC_COUNT] = {")
for i in range(0, len(names), 8):
    w("    " + " ".join('"%s",' % n for n in names[i:i + 8]))
w("};")
w("")
w("/* every label, sorted by bytes: a run of html_enc_label_text and its encoding */")
w("#define HTML_ENC_LABEL_COUNT %d" % len(labels))
w("#define HTML_ENC_LABEL_LONGEST %d" % max(len(l) for l, _ in labels))
w("static const char html_enc_label_text[] =")
for i in range(0, len(blob), 96):
    w('    "%s"' % blob[i:i + 96])
w(";")
w("static const struct html_enc_label { uint16_t off; uint8_t len; uint8_t enc; } html_enc_labels[HTML_ENC_LABEL_COUNT] = {")
off, row = 0, []
for l, e in labels:
    row.append("{ %d, %d, %s }," % (off, len(l), c_name(names[e])))
    off += len(l)
    if len(row) == 4:
        w("    " + " ".join(row))
        row = []
if row:
    w("    " + " ".join(row))
w("};")
w("")
w("/* index single-byte of each single-byte encoding: the code points of the bytes 0x80 to 0xFF */")
w("static const uint16_t html_enc_single[%d][128] = {" % len(single))
for n, t in zip(single, single_tables):
    w("    /* %s */ {" % n)
    for i in range(0, 128, 16):
        w("        " + ",".join(str(v) for v in t[i:i + 16]) + ",")
    w("    },")
w("};")
w("")
w("/* index jis0208, by pointer: Shift_JIS, EUC-JP and ISO-2022-JP read it */")
array("uint16_t", "html_enc_jis0208", dense(jis0208, JIS0208_SIZE))
w("/* index jis0212: EUC-JP's after 0x8F */")
array("uint16_t", "html_enc_jis0212", dense(jis0212, JIS0212_SIZE))
w("/* index EUC-KR */")
array("uint16_t", "html_enc_euc_kr", dense(euc_kr, EUC_KR_SIZE))
w("/* index gb18030: gb18030's (and GBK's) two-byte sequences */")
array("uint16_t", "html_enc_gb18030", dense(gb18030, GB18030_SIZE))
w("/* index Big5: each code point's low 16 bits; html_enc_big5_plane2 has bit p set when")
w("   pointer p's code point is in plane 2, 0x20000 more */")
b5 = [big5.get(p, 0) for p in range(BIG5_SIZE)]
assert all(v <= 0xFFFF or v >> 16 == 2 for v in b5)
assert all(v & 0xFFFF for v in b5 if v > 0xFFFF)     # so 0 still means none
array("uint16_t", "html_enc_big5", [v & 0xFFFF for v in b5])
bits = [0] * ((BIG5_SIZE + 7) // 8)
for p, v in enumerate(b5):
    if v > 0xFFFF:
        bits[p >> 3] |= 1 << (p & 7)
array("uint8_t", "html_enc_big5_plane2", bits, per=32)
w("/* index gb18030 ranges: a pointer and its code point, each the start of a range */")
rk = sorted(ranges)
w("#define HTML_ENC_GB18030_RANGES %d" % len(rk))
w("static const uint32_t html_enc_gb18030_ranges[%d][2] = {" % len(rk))
for i in range(0, len(rk), 8):
    w("    " + " ".join("{ %d, %d }," % (p, ranges[p]) for p in rk[i:i + 8]))
w("};")
sys.stdout.write("\n".join(out) + "\n")
